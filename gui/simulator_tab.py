from __future__ import annotations
from PyQt5.QtCore import pyqtSignal, Qt
from PyQt5.QtWidgets import (QWidget, QVBoxLayout, QHBoxLayout, QGridLayout, QPushButton,
                             QComboBox, QLineEdit)
from core.models import Command, CommandKind
from gui.widgets import Card, label, spin


class SimulatorTab(QWidget):
    command_requested = pyqtSignal(object)
    scenario_requested = pyqtSignal(str)
    action_requested = pyqtSignal(str, object)

    def __init__(self, scenarios: tuple[str, ...]) -> None:
        super().__init__()
        self.setObjectName('Page')
        layout = QVBoxLayout(self)
        layout.setContentsMargins(22, 18, 22, 20)
        layout.setSpacing(14)
        layout.addWidget(label('Simulation lab', 'PageTitle'))
        layout.addWidget(label('A virtual cube, synthetic camera and reference controller. No ESP32 is required.'))
        layout.addWidget(label('DEMONSTRATOR ONLY  |  Assumed inertia and actuator limits. Passing here does not validate the real firmware or hardware.', 'Warning'))
        columns = QHBoxLayout()
        left, right = QVBoxLayout(), QVBoxLayout()
        runtime = Card('Local runtime', 'Physics advances in fixed substeps; results use the simulation clock.')
        row = QHBoxLayout()
        self.arm = QPushButton('Arm SIM'); self.arm.setObjectName('Primary')
        self.disarm = QPushButton('Disarm SIM')
        self.pause = QPushButton('Pause physics'); self.pause.setCheckable(True)
        for b in [self.arm, self.disarm, self.pause]:
            row.addWidget(b)
        runtime.box.addLayout(row)
        self.arm.clicked.connect(lambda: self.command_requested.emit(Command(CommandKind.ARM)))
        self.disarm.clicked.connect(lambda: self.command_requested.emit(Command(CommandKind.DISARM)))
        self.pause.toggled.connect(self.toggle_pause)
        self.clock = label('SIM time 0.00 s', 'CardTitle')
        runtime.box.addWidget(self.clock)
        controls = QGridLayout()
        controls.addWidget(label('Time scale'), 0, 0)
        self.speed = QComboBox(); self.speed.addItems(['1x', '2x', '4x'])
        controls.addWidget(self.speed, 0, 1)
        self.speed.currentTextChanged.connect(lambda text: self.action_requested.emit('speed', float(text[:-1])))
        controls.addWidget(label('Displayed attitude noise [deg]'), 1, 0)
        self.noise = spin(0., 2., .04, decimals=2, step=.01)
        self.noise.valueChanged.connect(lambda value: self.action_requested.emit('noise', value))
        controls.addWidget(self.noise, 1, 1)
        runtime.box.addLayout(controls)
        runtime.box.addWidget(label('Noise affects displayed synthetic sensors, not the idealized control estimate. This is not a sensor-fusion validation.'))
        left.addWidget(runtime)
        scenario = Card('Repeatable scenarios', 'Load while disarmed, then press Arm SIM to begin.')
        self.scenario_combo = QComboBox(); self.scenario_combo.addItems(list(scenarios))
        scenario.box.addWidget(self.scenario_combo)
        self.load_button = QPushButton('Load selected scenario')
        self.load_button.clicked.connect(lambda: self.scenario_requested.emit(self.scenario_combo.currentText()))
        scenario.box.addWidget(self.load_button)
        self.score = label('MANUAL', 'Badge', False)
        scenario.box.addWidget(self.score, alignment=Qt.AlignLeft)
        self.score_detail = label('Free exploration. No automatic acceptance result.')
        scenario.box.addWidget(self.score_detail)
        self.metrics = label('Elapsed --   |   Max error --   |   Time in band --')
        scenario.box.addWidget(self.metrics)
        scenario.box.addWidget(label('Scores use model truth, not received telemetry.\nCapture/recovery: +/-2 deg with 0.25 s dwell is a declared demo criterion.\nMoving-target and occlusion runs require trace review; no invented PASS threshold.'))
        left.addWidget(scenario)
        faults = Card('Disturbances & link tests', 'The virtual onboard loop keeps running during telemetry loss.')
        nudge = QHBoxLayout()
        self.nudge_axis = QComboBox(); self.nudge_axis.addItems(['Roll / X', 'Pitch / Y', 'Yaw / Z']); self.nudge_axis.setCurrentIndex(2)
        self.nudge_value = spin(-45., 45., 20., step=5.); self.nudge_value.setSuffix(' deg')
        self.nudge_button = QPushButton('Apply nudge')
        nudge.addWidget(self.nudge_axis); nudge.addWidget(self.nudge_value); nudge.addWidget(self.nudge_button)
        faults.box.addLayout(nudge)
        self.nudge_button.clicked.connect(lambda: self.action_requested.emit('nudge',
            (self.nudge_axis.currentIndex(), self.nudge_value.value())))
        self.hide_button = QPushButton('Hide camera target for 2 s')
        self.hide_button.clicked.connect(lambda: self.action_requested.emit('occlude', 2.))
        self.drop_button = QPushButton('Drop received telemetry for 2 s')
        self.drop_button.clicked.connect(lambda: self.action_requested.emit('drop', 2.))
        faults.box.addWidget(self.hide_button); faults.box.addWidget(self.drop_button)
        faults.box.addWidget(label('The nudge changes orientation instantaneously; it is not a calibrated mechanical force. Extra disturbances invalidate an automatic score.'))
        right.addWidget(faults)
        link = Card('Future ESP32 connection', 'Wi-Fi / UDP is planned. Real hardware is deliberately disabled.')
        form = QGridLayout()
        self.endpoint = QLineEdit(); self.endpoint.setPlaceholderText('ESP32 IP - pending team ICD'); self.endpoint.setEnabled(False)
        self.port = QLineEdit(); self.port.setPlaceholderText('UDP ports - pending team ICD'); self.port.setEnabled(False)
        form.addWidget(label('Remote address'), 0, 0); form.addWidget(self.endpoint, 0, 1)
        form.addWidget(label('Remote / local port'), 1, 0); form.addWidget(self.port, 1, 1)
        link.box.addLayout(form)
        self.connect_button = QPushButton('Connect ESP32 - ICD not implemented')
        self.connect_button.setEnabled(False)
        link.box.addWidget(self.connect_button)
        link.box.addWidget(label('Insertion point: communication/protocol_adapter.py\nNo fabricated packet layout, CRC or ACK. BLE is not implemented.'))
        right.addWidget(link)
        note = Card('Camera tracking: what it proves')
        note.box.addWidget(label('The simulator draws a white spot, detects its pixels and estimates its centre. Pitch/Yaw point toward it. Roll is held at an inertial reference of 0 deg.'))
        note.box.addWidget(label('One point alone does not define rotation about the viewing direction. The real vision/control algorithms remain onboard.'))
        right.addWidget(note)
        left.addStretch(); right.addStretch()
        columns.addLayout(left, 1); columns.addLayout(right, 1)
        layout.addLayout(columns)
        layout.addStretch()

    def toggle_pause(self, paused: bool) -> None:
        self.pause.setText('Resume physics' if paused else 'Pause physics')
        self.action_requested.emit('pause', paused)

    def update_status(self, engine, runner, paused: bool) -> None:
        self.clock.setText(f'SIM time {engine.time:.2f} s' + (' / PAUSED' if paused else ' / RUNNING'))
        self.score.setText(runner.status)
        self.score_detail.setText(runner.detail)
        self.metrics.setText(f'Elapsed {runner.elapsed:.2f} s  |  Max error {runner.max_error:.2f} deg  |  In band {runner.in_band:.2f} s')
        self.arm.setEnabled(not engine.armed and not engine.estop)
        self.disarm.setEnabled(engine.armed)
        self.load_button.setEnabled(not engine.armed and not engine.estop)
        self.nudge_button.setEnabled(not engine.estop)
